import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const layout = await readFile(new URL('layouts/page.html', root), 'utf8');
export const screens = [
  { name: 'home', file: 'index.html', title: 'Pushpika Anuradha — Software Engineer' },
  { name: 'about', file: 'about.html', title: 'About — Pushpika Anuradha' },
  { name: 'projects', file: 'projects.html', title: 'Projects — Pushpika Anuradha' },
  { name: 'contact', file: 'contact.html', title: 'Contact — Pushpika Anuradha' },
];
export async function renderScreen(screen) {
  const isHome = screen.name === 'home';
  const values = {
    screen: (await readFile(new URL(`screens/${screen.name}.html`, root), 'utf8')).trim(),
    title: screen.title, page: screen.name,
    header: ['projects', 'contact'].includes(screen.name) ? '' : '<header class="main-header"><a class="wordmark" href="index.html">Pushpika<span>↗</span></a><a class="contact-pill" href="contact.html">Let’s talk <span>●</span></a></header>',
    entranceClass: isHome ? '' : ' dismissed',
    entranceAttributes: isHome ? '' : 'inert aria-hidden="true"',
    portfolioClass: isHome ? '' : ' active',
    portfolioAttributes: isHome ? 'inert aria-hidden="true"' : '',
  };
  const entrance = await readFile(new URL('screens/entrance.html', root), 'utf8');
  let html = layout.replace('{{entrance}}', entrance.trim()).replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!(key in values)) throw new Error(`Unknown template field: ${key}`);
    return values[key];
  });
  html = html.replace(`data-page="${screen.name}">${screen.name === 'home' ? 'Home' : screen.name[0].toUpperCase() + screen.name.slice(1)}</a>`,
    `data-page="${screen.name}" aria-current="page">${screen.name[0].toUpperCase() + screen.name.slice(1)}</a>`);
  return '<!-- Generated by npm run build. Edit screens/ and layouts/page.html. -->\n' + html;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const screen of screens) await writeFile(new URL(screen.file, root), await renderScreen(screen));
  console.log('Built Home, About, Projects, and Contact.');
}
